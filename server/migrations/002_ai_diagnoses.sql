CREATE TABLE IF NOT EXISTS ai_diagnoses (
  id VARCHAR(191) NOT NULL PRIMARY KEY,
  workshop_id VARCHAR(191) NOT NULL,
  customer_id VARCHAR(191) NOT NULL,
  vehicle_id VARCHAR(191) NOT NULL,
  job_id VARCHAR(191),
  reported_symptoms TEXT NOT NULL,
  predicted_fault TEXT NOT NULL,
  confidence DOUBLE NOT NULL,
  prediction_candidates_json LONGTEXT NOT NULL,
  review_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  confirmed_fault TEXT,
  mechanic_notes TEXT,
  created_by_user_id VARCHAR(191) NOT NULL,
  created_by_name VARCHAR(255) NOT NULL,
  created_at VARCHAR(40) NOT NULL,
  reviewed_at VARCHAR(40),
  KEY ai_diagnoses_workshop_vehicle_created_idx (workshop_id, vehicle_id, created_at),
  KEY ai_diagnoses_workshop_job_idx (workshop_id, job_id),
  CONSTRAINT ai_diagnoses_workshop_fk FOREIGN KEY (workshop_id) REFERENCES workshops(id) ON DELETE CASCADE,
  CONSTRAINT ai_diagnoses_customer_fk FOREIGN KEY (customer_id, workshop_id) REFERENCES customers(id, workshop_id) ON DELETE CASCADE,
  CONSTRAINT ai_diagnoses_vehicle_fk FOREIGN KEY (vehicle_id, workshop_id) REFERENCES vehicles(id, workshop_id) ON DELETE CASCADE,
  CONSTRAINT ai_diagnoses_job_fk FOREIGN KEY (job_id, workshop_id) REFERENCES jobs(id, workshop_id) ON DELETE RESTRICT,
  CONSTRAINT ai_diagnoses_user_fk FOREIGN KEY (created_by_user_id, workshop_id) REFERENCES users(id, workshop_id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
